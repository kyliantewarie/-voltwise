"""Offline licence validation with public-key signatures and device binding.

The vendor keeps the Ed25519 **private** key; only the public key ships in the
product. A customer cannot mint a licence by reading an environment variable.
Premium features are always gated; offline licensing is still not absolute DRM,
so sell the support and update channel rather than the cryptographic boundary.
"""

from __future__ import annotations

import base64
import binascii
import hashlib
import json
import math
import platform
import time
import uuid
from dataclasses import dataclass
from pathlib import Path

try:  # cryptography is a declared runtime dependency
    from cryptography.exceptions import InvalidSignature
    from cryptography.hazmat.primitives import serialization
    from cryptography.hazmat.primitives.asymmetric.ed25519 import (
        Ed25519PrivateKey,
        Ed25519PublicKey,
    )
except ImportError:  # pragma: no cover - installation guard
    InvalidSignature = ValueError  # type: ignore[misc,assignment]
    serialization = None  # type: ignore[assignment]
    Ed25519PrivateKey = None  # type: ignore[misc,assignment]
    Ed25519PublicKey = None  # type: ignore[misc,assignment]

# Public key generated by the vendor. Replace with your own release key.
PUBLIC_KEY_B64 = "SzDzVmXxeINuplpRva12jYBRFZnSzohjiDeL0du1VYA="


@dataclass(frozen=True, slots=True)
class Licence:
    subject: str
    features: frozenset[str]
    expires_epoch: float
    hwid: str | None = None

    def allows(self, feature: str, hwid: str | None = None) -> bool:
        if feature not in self.features or self.expires_epoch <= time.time():
            return False
        if self.hwid is not None:
            if not isinstance(self.hwid, str) or not self.hwid:
                return False
            if hwid != self.hwid:
                return False
        return True


def current_hwid(seed: str = "") -> str:
    """Best-effort device fingerprint from non-user-controlled inputs."""
    machine = ""
    candidate = Path("/etc/machine-id")
    if candidate.is_file():
        try:
            machine = candidate.read_text(encoding="utf-8").strip()
        except OSError:
            machine = ""
    raw = f"{platform.node()}|{machine}|{uuid.getnode()}|{seed}"
    return hashlib.sha256(raw.encode("utf-8")).hexdigest()[:20]


def _b64url(raw: bytes) -> str:
    return base64.urlsafe_b64encode(raw).decode("ascii").rstrip("=")


def _unb64url(text: str) -> bytes:
    """Strict canonical base64url decoding."""
    text = text.rstrip("=") if isinstance(text, str) else text
    if not isinstance(text, str) or not text or any(ch not in "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789-_" for ch in text):
        raise ValueError("invalid base64url")
    decoded = base64.urlsafe_b64decode(text + "=" * (-len(text) % 4))
    if _b64url(decoded) != text:
        raise ValueError("non-canonical base64url")
    return decoded


def encode_licence(payload: dict, private_key_pem: str | bytes) -> str:
    """Sign a licence payload with the vendor's Ed25519 private key."""
    if serialization is None or Ed25519PrivateKey is None:
        raise RuntimeError("cryptography is required to sign licences")
    if isinstance(private_key_pem, str):
        private_key_pem = private_key_pem.encode("utf-8")
    key = serialization.load_pem_private_key(private_key_pem, password=None)
    if not isinstance(key, Ed25519PrivateKey):
        raise ValueError("licence key must be Ed25519")
    body = _b64url(
        json.dumps(payload, separators=(",", ":"), sort_keys=True, allow_nan=False).encode("utf-8")
    )
    return f"{body}.{_b64url(key.sign(body.encode('ascii')))}"


def decode_licence(key: str) -> Licence | None:
    """Verify a licence with the embedded public key and parse it."""
    if Ed25519PublicKey is None or not isinstance(key, str):
        return None
    try:
        body, signature = key.split(".", 1)
        public_key = Ed25519PublicKey.from_public_bytes(_unb64url(PUBLIC_KEY_B64))
        public_key.verify(_unb64url(signature), body.encode("ascii"))
        payload = json.loads(_unb64url(body))
        expires = float(payload.get("exp", 0))
        if not math.isfinite(expires) or expires <= 0:
            return None
        hwid = payload.get("hwid")
        if hwid is not None and (not isinstance(hwid, str) or not hwid):
            return None
        return Licence(
            subject=str(payload["sub"]),
            features=frozenset(payload.get("features", [])),
            expires_epoch=expires,
            hwid=hwid,
        )
    except (ValueError, KeyError, TypeError, OverflowError, InvalidSignature, binascii.Error):
        return None


def check_licence(
    key: str | None,
    feature: str,
    *,
    require: bool = False,
    hwid: str | None = None,
) -> tuple[bool, str]:
    """Return (allowed, reason). Missing keys are denied when enforcement is on."""
    if not key:
        return (False, "licence key missing") if require else (True, "enforcement disabled")
    licence = decode_licence(key)
    if licence is None:
        return False, "licence signature invalid"
    if not licence.allows(feature, hwid):
        return False, f"licence does not allow feature {feature!r}, expired, or bound to another device"
    return True, "valid"
